import type { GeneratedFile } from "./types";

export function detectShadcn(files: GeneratedFile[]): string[] {
  const set = new Set<string>();
  for (const f of files) {
    for (const m of f.code.matchAll(/@\/components\/ui\/([\w-]+)/g)) set.add(m[1]);
  }
  return [...set].sort();
}

export function shadcnCommand(files: GeneratedFile[]): string {
  const ui = detectShadcn(files);
  return ui.length ? `npx shadcn@latest add ${ui.join(" ")}` : "";
}

export function filesToText(files: GeneratedFile[]): string {
  return files.map((f) => `// ===== ${f.path} =====\n${f.code}`).join("\n");
}

export async function filesToZip(files: GeneratedFile[]): Promise<Blob> {
  // Loaded on demand: only users who export a ZIP pay for the library.
  const { default: JSZip } = await import("jszip");
  const zip = new JSZip();
  for (const f of files) zip.file(f.path, f.code);
  const cmd = shadcnCommand(files);
  zip.file(
    "README.md",
    `# Generated by Snap to Code\n\nCopy \`components/\` and \`app/page.tsx\` into a Next.js + Tailwind project.\n\n${
      cmd ? `Install the shadcn/ui components used:\n\n\`\`\`bash\n${cmd}\n\`\`\`\n` : ""
    }\nIcons: \`npm i lucide-react\`\n`,
  );
  return zip.generateAsync({ type: "blob" });
}

/** The file name without its folders: browsers ignore folders in a download name. */
export function baseName(path: string): string {
  return path.split("/").pop() || path;
}

export function downloadBlob(blob: Blob, name: string) {
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}
